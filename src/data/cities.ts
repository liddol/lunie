const LOCAL_STORAGE_KEY = "luna-city";

export function getSavedCity(): City | null {
  try {
    const raw = localStorage.getItem(LOCAL_STORAGE_KEY);
    if (!raw) return null;
    const parsed = JSON.parse(raw);
    return CITIES.find(c => c.name === parsed.name) ?? null;
  } catch {
    return null;
  }
}

export function saveCity(city: City | null): void {
  try {
    if (city) {
      localStorage.setItem(LOCAL_STORAGE_KEY, JSON.stringify(city));
    } else {
      localStorage.removeItem(LOCAL_STORAGE_KEY);
    }
  } catch {
    // ignore
  }
}
